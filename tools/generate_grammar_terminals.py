"""Generate ``terminals.lark`` from :mod:`oq.core.tokens`.

Run from the repository root::

    uv run python tools/generate_grammar_terminals.py

The test suite regenerates the file in memory and fails if it drifts, so the
token definitions have exactly one source of truth.
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "packages" / "oq-core" / "src"))

from oq.core.tokens import TokenKind  # noqa: E402

TARGET = ROOT / "packages" / "oq-core" / "src" / "oq" / "core" / "grammar" / "terminals.lark"

HEADER = """\
// Generated by tools/generate_grammar_terminals.py from oq.core.tokens.
// Do not edit by hand. A test fails if this file drifts from TokenKind.
// Terminals are declared, not defined: the lexer in oq.core.tokens is the only
// implementation that produces them.
"""


def render() -> str:
    lines = [HEADER]
    for kind in TokenKind:
        lines.append(f"%declare {kind.value}\n")
    for kind in HIDDEN_TERMINALS:
        lines.append(f"%declare _{kind}\n")
    return "".join(lines)


def main() -> None:
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(render(), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
