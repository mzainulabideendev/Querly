class OracleConnection(Connection):
    def __init__(self, config: ConnectionConfig, conn: Any) -> None:
        self._config = config
        self._conn = conn
        self._closed = False

    @property
    def config(self) -> ConnectionConfig:
        return self._config

    @property
    def is_closed(self) -> bool:
        return self._closed

    def ping(self) -> bool:
        try:
            self._conn.ping()
            return True
        except Exception:
            return False

    def execute(self, sql: str, params: Any = None) -> Any:
        cursor = self._conn.cursor()
        cursor.execute(sql, params or {})
        return cursor

    def close(self) -> None:
        if not self._closed:
            self._conn.close()
            self._closed = True

    @property
    def raw_connection(self) -> Any:
        return self._conn


class OracleTransaction(Transaction):
    def __init__(self, connection: OracleConnection, options: TransactionOptions) -> None:
        self._connection = connection
        self._options = options
        self._active = True

    @property
    def connection(self) -> Connection:
        return self._connection

    @property
    def is_active(self) -> bool:
        return self._active and not self._connection.is_closed

    def commit(self) -> None:
        if self._active:
            self._connection.raw_connection.commit()
            self._active = False

    def rollback(self) -> None:
        if self._active:
            self._connection.raw_connection.rollback()
            self._active = False


class OracleAdapter(Adapter):
    data_model = "relational"
    ir_subset = ("schema", "select")

    def __init__(self) -> None:
        self.dialect = OracleDialect()

    @property
    def id(self) -> str:
        return "oracle"

    @property
    def display_name(self) -> str:
        return "Oracle Database"

    @property
    def package_version(self) -> str:
        from oq_adapters.oracle import __version__

        return __version__

    def capabilities(self) -> CapabilityReport:
        from oq_adapters.oracle import __version__

        return build_report(
            adapter=self.id,
            adapter_version=__version__,
            engine="Oracle Database",
            tested_versions=[],
            capabilities=ORACLE_CAPS,
            types=ORACLE_TYPES,
            limitations=[
                "No tested engine version is claimed in this environment.",
                "DDL implicitly commits.",
                "Oracle DATE includes a time component; it is not a pure calendar date.",
                "Identity columns require Oracle 12c or later.",
            ],
        )

    def connect(self, config: ConnectionConfig, *, secrets: SecretProvider) -> Connection:
        if config.adapter != "oracle":
            raise AdapterError(AdapterErrorCode.CONNECTION, "Expected an oracle config.")
        if oracledb is None:
            raise AdapterError(
                AdapterErrorCode.CONNECTION,
                "oracledb is not installed. Install oq-adapter-oracle[driver].",
            )
        dsn = config.options.get("dsn")
        if not dsn:
            if not config.host:
                raise AdapterError(AdapterErrorCode.CONNECTION, "Oracle requires a host or DSN.")
            dsn = f"{config.host}:{config.port or 1521}/{config.database or config.options.get('service_name', 'ORCL')}"
        try:
            raw = oracledb.connect(
                user=config.user,
                password=secrets.get("password"),
                dsn=dsn,
                config_dir=config.options.get("config_dir"),
                wallet_location=config.options.get("wallet_location"),
            )
        except Exception as exc:
            raise self._error(exc, "connect") from exc
        return OracleConnection(config, raw)

    def detect_version(self, connection: Connection) -> EngineVersion:
        conn = self._require(connection)
        cursor = conn.execute("SELECT banner_full FROM v$version WHERE banner_full LIKE 'Oracle Database%'")
        try:
            row = cursor.fetchone()
            raw = str(row[0]) if row else "Oracle Database"
        finally:
            cursor.close()
        import re

        version = re.search(r"(\d+)\.(\d+)\.(\d+)", raw)
        return EngineVersion(
            product="Oracle Database",
            version=raw,
            major=int(version.group(1)) if version else 0,
            minor=int(version.group(2)) if version else 0,
            patch=int(version.group(3)) if version else 0,
        )

    def close(self, connection: Connection) -> None:
        if isinstance(connection, OracleConnection):
            try:
                connection.close()
            except Exception:
                pass

    def inspect_schema(self, connection: Connection) -> SchemaDocument:
        conn = self._require(connection)
        owner = (conn.config.user or "").upper()
        tables = self._fetch(
            conn,
            "SELECT table_name FROM all_tables WHERE owner = :owner ORDER BY table_name",
            {"owner": owner},
        )
        columns = self._fetch(
            conn,
            """
            SELECT table_name, column_name, data_type, data_length, data_precision,
                   data_scale, nullable, data_default, identity_column
            FROM all_tab_columns
            WHERE owner = :owner
            ORDER BY table_name, column_id
            """,
            {"owner": owner},
        )
        constraints = self._fetch(
            conn,
            """
            SELECT c.table_name, c.constraint_name, c.constraint_type, cc.column_name,
                   cc.position, r.table_name, rcc.column_name
            FROM all_constraints c
            JOIN all_cons_columns cc ON cc.owner = c.owner AND cc.constraint_name = c.constraint_name
            LEFT JOIN all_constraints r ON r.owner = c.r_owner AND r.constraint_name = c.r_constraint_name
            LEFT JOIN all_cons_columns rcc ON rcc.owner = r.owner AND rcc.constraint_name = r.constraint_name
                                      AND rcc.position = cc.position
            WHERE c.owner = :owner AND c.constraint_type IN ('P','U','R')
            ORDER BY c.table_name, c.constraint_name, cc.position
            """,
            {"owner": owner},
        )
        indexes = self._fetch(
            conn,
            """
            SELECT i.table_name, i.index_name, i.uniqueness, ic.column_name, ic.column_position, i.index_type
            FROM all_indexes i
            JOIN all_ind_columns ic ON ic.index_owner = i.owner AND ic.index_name = i.index_name
            WHERE i.owner = :owner
            ORDER BY i.table_name, i.index_name, ic.column_position
            """,
            {"owner": owner},
        )
        by_table: dict[str, list[tuple[Any, ...]]] = {}
        for row in columns:
            by_table.setdefault(str(row[0]), []).append(row)
        pk_map: dict[str, list[str]] = {}
        for row in constraints:
            if str(row[2]) == "P":
                pk_map.setdefault(str(row[0]), []).append(str(row[3]))
        entities: list[Entity] = []
        for (table,) in tables:
            attributes = []
            for row in by_table.get(str(table), []):
                _, name, data_type, length, precision, scale, nullable, default, identity = row
                kind, type_obj = _oracle_type(str(data_type), length, precision, scale)
                attributes.append(
                    Attribute(
                        name=str(name),
                        type=type_obj,
                        nullable=str(nullable).upper() == "Y",
                        primary=str(name) in pk_map.get(str(table), []),
                        auto=str(identity).upper() == "YES",
                        default=default,
                    )
                )
            entities.append(
                Entity(
                    name=str(table),
                    attributes=attributes,
                    primary_key=pk_map.get(str(table), []),
                    indexes=_oracle_indexes(str(table), indexes),
                    constraints=_oracle_constraints(str(table), constraints),
                )
            )
        return SchemaDocument(entities=entities, enums=[], extensions=[])

    def compile_schema(self, schema: SchemaDocument, options: CompileOptions | None) -> list[DDLArtifact]:
        result = compile_schema_sql(self.dialect, schema, options or CompileOptions())
        if not result.supported:
            raise AdapterError(
                AdapterErrorCode.CAPABILITY,
                "Oracle cannot compile part of the schema.",
                diagnostics=[item.model_dump(mode="json") for item in result.diagnostics],
            )
        return result.artifacts

    def compile_query(self, query: QueryDocument, schema: SchemaDocument, options: CompileOptions | None = None) -> PlanDocument:
        result = compile_select_sql(self.dialect, query, schema, options=options)
        parameters = [dict(item) for item in result.parameters]
        return PlanDocument(
            target_adapter=self.id,
            operation=query.operation,
            artifact=Artifact(kind="sql", text=result.sql, dialect="oracle", placeholders=parameters),
            parameters=parameters,
            required_capabilities=[CAP_JOINS] if query.joins else [],
            safety=query.safety,
            result_columns=result.result_columns,
            engine_plan={"kind": "sql", "sql": result.sql, "parameter_order": [p["name"] for p in parameters]},
            diagnostics=result.diagnostics,
            supported=result.supported,
        )

    def execute(self, connection: Connection, plan: PlanDocument, params: Mapping[str, Any]) -> ResultSet:
        conn = self._require(connection)
        if not plan.supported or not plan.artifact.text:
            raise AdapterError(
                AdapterErrorCode.CAPABILITY,
                "Plan is unsupported and was not executed.",
                diagnostics=[item.model_dump(mode="json") for item in plan.diagnostics],
            )
        binds = {str(entry["name"]): params[str(entry["name"])] for entry in plan.parameters}
        try:
            cursor = conn.execute(plan.artifact.text, binds)
        except Exception as exc:
            raise self._error(exc, "execute") from exc
        try:
            columns = [ResultColumn(str(c[0]), None, True) for c in cursor.description] if cursor.description else []
            rows = [ResultRow(tuple(_value(v) for v in row)) for row in cursor.fetchall()]
            affected = cursor.rowcount if cursor.rowcount is not None and cursor.rowcount >= 0 else None
        finally:
            cursor.close()
        return ResultSet(columns=columns, rows=rows, affected_rows=affected, warnings=[])

    def begin(self, connection: Connection, options: TransactionOptions | None = None) -> Transaction:
        conn = self._require(connection)
        opts = options or TransactionOptions()
        levels = {
            "read_uncommitted": "READ UNCOMMITTED",
            "read_committed": "READ COMMITTED",
            "repeatable_read": "SERIALIZABLE",
            "serializable": "SERIALIZABLE",
        }
        conn.execute(f"SET TRANSACTION ISOLATION LEVEL {levels[opts.isolation.value]}")
        if opts.read_only:
            conn.execute("SET TRANSACTION READ ONLY")
        return OracleTransaction(conn, opts)

    def commit(self, transaction: Transaction) -> None:
        if not isinstance(transaction, OracleTransaction):
            raise AdapterError(AdapterErrorCode.CONNECTION, "Wrong transaction type.")
        transaction.commit()

    def rollback(self, transaction: Transaction) -> None:
        if isinstance(transaction, OracleTransaction):
            try:
                transaction.rollback()
            except Exception:
                pass

    def _require(self, connection: Connection) -> OracleConnection:
        if not isinstance(connection, OracleConnection):
            raise AdapterError(AdapterErrorCode.CONNECTION, "Wrong connection type for Oracle.")
        return connection

    @staticmethod
    def _fetch(conn: OracleConnection, sql: str, params: dict[str, Any]) -> list[tuple[Any, ...]]:
        cursor = conn.execute(sql, params)
        try:
            return list(cursor.fetchall())
        finally:
            cursor.close()

    @staticmethod
    def _error(exc: BaseException, operation: str) -> AdapterError:
        text = redact_message(str(exc))
        code = AdapterErrorCode.CONNECTION
        retryable = False
        message = str(exc)
        if "ORA-00001" in message:
            code = AdapterErrorCode.CONSTRAINT
        elif "ORA-02291" in message or "ORA-02292" in message:
            code = AdapterErrorCode.CONSTRAINT
        elif "ORA-01017" in message or "ORA-01031" in message:
            code = AdapterErrorCode.AUTH
        elif "ORA-00942" in message or "ORA-00933" in message or "ORA-00936" in message:
            code = AdapterErrorCode.SYNTAX
        elif "ORA-12170" in message or "ORA-12541" in message or "DPY-6005" in message:
            retryable = True
        elif "ORA-01013" in message:
            code = AdapterErrorCode.CANCELLED
        return AdapterError(code, f"Oracle {operation} failed: {text}", retryable=retryable, cause=exc, redacted_cause=text)


def _oracle_type(native: str, length: Any, precision: Any, scale: Any) -> tuple[str, Type]:
    name = native.upper()
    if name in ("NUMBER", "INTEGER", "INT"):
        if precision and int(precision) <= 10 and (scale in (None, 0, "0")):
            return "integer", Type(kind="integer")
        if precision and int(precision) > 10:
            return "bigint", Type(kind="bigint")
        return "decimal", Type(kind="decimal", precision=int(precision) if precision else None, scale=int(scale) if scale is not None else None)
    if name in ("BINARY_FLOAT", "FLOAT"):
        return "float", Type(kind="float")
    if name in ("BINARY_DOUBLE", "DOUBLE PRECISION"):
        return "double", Type(kind="double")
    if name in ("VARCHAR2", "NVARCHAR2", "CHAR", "NCHAR", "CLOB", "NCLOB", "LONG"):
        return "text", Type(kind="text", max_length=int(length) if length and name not in ("CLOB", "NCLOB", "LONG") else None)
    if name == "DATE":
        return "date", Type(kind="date")
    if name.startswith("TIMESTAMP"):
        return "timestamp" if "TIME ZONE" in name else "datetime", Type(kind="timestamp" if "TIME ZONE" in name else "datetime", has_timezone="TIME ZONE" in name)
    if name.startswith("INTERVAL"):
        return "duration", Type(kind="duration")
    if name in ("RAW", "BLOB", "LONG RAW"):
        return "binary", Type(kind="binary")
    if name == "JSON":
        return "json", Type(kind="json")
    if name == "SDO_GEOMETRY":
        return "geo", Type(kind="geo")
    if name.startswith("VECTOR"):
        return "vector", Type(kind="vector")
    return "text", Type(kind="text")


def _oracle_indexes(table: str, rows: list[tuple[Any, ...]]) -> list[Index]:
    grouped: dict[str, list[tuple[Any, ...]]] = {}
    for row in rows:
        if str(row[0]) == table:
            grouped.setdefault(str(row[1]), []).append(row)
    return [
        Index(
            name=name,
            columns=[str(item[3]) for item in sorted(items, key=lambda item: int(item[4] or 0))],
            unique=str(items[0][2]).upper() == "UNIQUE",
            kind="btree" if "NORMAL" in str(items[0][5]).upper() else str(items[0][5]).lower(),
        )
        for name, items in grouped.items()
    ]


def _oracle_constraints(table: str, rows: list[tuple[Any, ...]]) -> list[Constraint]:
    grouped: dict[str, list[tuple[Any, ...]]] = {}
    for row in rows:
        if str(row[0]) == table and str(row[2]) == "R":
            grouped.setdefault(str(row[1]), []).append(row)
    return [
        Constraint(
            kind="foreign_key",
            columns=[str(item[3]) for item in items],
            reference=str(items[0][5]),
            referenced_columns=[str(item[6]) for item in items if item[6] is not None],
        )
        for items in grouped.values()
    ]


def _value(value: Any) -> Any:
    if isinstance(value, memoryview):
        return bytes(value)
    if isinstance(value, (Decimal, date, datetime, time, bytes)):
        return value
    return value
