class OracleDialect(SqlDialect):
    adapter_id = "oracle"
    engine = "Oracle Database"
    quote_open = '"'
    quote_close = '"'
    max_identifier_length = 128
    placeholder_style = "named"
    supports_full_join = True
    supports_null_ordering = True
    supports_ilike = False
    supports_returning = False
    supports_auto_increment = True

    def type_sql(self, type_obj: Any) -> str | None:
        kind = type_kind(type_obj)
        if kind in ("integer", "int"):
            return "NUMBER(10)"
        if kind in ("bigint", "reference"):
            return "NUMBER(19)"
        if kind == "float":
            return "BINARY_FLOAT"
        if kind == "double":
            return "BINARY_DOUBLE"
        if kind == "decimal":
            precision = getattr(type_obj, "precision", None)
            scale = getattr(type_obj, "scale", None)
            if precision and scale is not None:
                return f"NUMBER({min(int(precision), 38)},{min(int(scale), 38)})"
            return "NUMBER(38,9)"
        if kind == "text":
            length = getattr(type_obj, "max_length", None)
            if length and length <= 4000:
                return f"VARCHAR2({length})"
            return "CLOB"
        if kind == "boolean":
            return "NUMBER(1)"
        if kind == "date":
            return "DATE"
        if kind == "time":
            return "INTERVAL DAY(0) TO SECOND(6)"
        if kind in ("timestamp", "datetime"):
            return "TIMESTAMP(6) WITH TIME ZONE" if getattr(type_obj, "has_timezone", False) else "TIMESTAMP(6)"
        if kind == "duration":
            return "INTERVAL DAY(9) TO SECOND(6)"
        if kind == "uuid":
            return "RAW(16)"
        if kind == "email":
            return "VARCHAR2(320)"
        if kind == "url":
            return "VARCHAR2(2048)"
        if kind in ("json", "map", "list", "set"):
            return "CLOB"
        if kind == "binary":
            return "BLOB"
        if kind == "geo":
            return "SDO_GEOMETRY"
        if kind == "vector":
            dimension = getattr(type_obj, "dimension", None)
            return f"VECTOR({int(dimension)}, FLOAT32)" if dimension else None
        if kind == "enum":
            return "VARCHAR2(255)"
        return None

    def auto_sql(self, attr: Any, type_sql: str) -> str | None:
        if type_kind(attr.type) not in ("integer", "int", "bigint"):
            return None
        return "GENERATED BY DEFAULT ON NULL AS IDENTITY"

    def select_limit(
        self, sql: str, limit: int | None, offset: int | None, has_order_by: bool
    ) -> tuple[str, list]:
        if limit is None and offset is None:
            return sql, []
        if offset is not None:
            sql += f" OFFSET {int(offset)} ROWS"
        if limit is not None:
            sql += f" FETCH NEXT {int(limit)} ROWS ONLY"
        return sql, []

    def bind_placeholder(self, index: int, hint: str, label: str) -> str:
        return f":{label}"


