"""CockroachDB adapter for Querly.

CockroachDB speaks the PostgreSQL wire protocol but is not PostgreSQL: it has
transactional schema changes, no user-defined functions in the PostgreSQL
sense, different catalog performance characteristics, and its own retryable
serialization errors (SQLSTATE 40001). This adapter uses psycopg 3, CockroachDB
DDL and type names, and CockroachDB's ``information_schema``.

It is a distinct adapter from a future ``postgres`` adapter; capability claims
are CockroachDB's own.
"""

