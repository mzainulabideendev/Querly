class CockroachDBConnection(Connection):
    def __init__(self, config: ConnectionConfig, conn: Any) -> None:
        self._config = config
        self._conn = conn
        self._closed = False

    @property
    def config(self) -> ConnectionConfig:
        return self._config

    @property
    def is_closed(self) -> bool:
        return self._closed

    def ping(self) -> bool:
        try:
            with self._conn.cursor() as cursor:
                cursor.execute("SELECT 1")
                cursor.fetchone()
            return True
        except Exception:
            return False

    def execute(self, sql: str, params: tuple[Any, ...] = ()) -> Any:
        cursor = self._conn.cursor()
        cursor.execute(sql, params or None)
        return cursor

    def close(self) -> None:
        if not self._closed:
            self._conn.close()
            self._closed = True

    @property
    def raw_connection(self) -> Any:
        return self._conn


class CockroachDBTransaction(Transaction):
    def __init__(self, connection: CockroachDBConnection, options: TransactionOptions) -> None:
        self._connection = connection
        self._options = options
        self._active = True

    @property
    def connection(self) -> Connection:
        return self._connection

    @property
    def is_active(self) -> bool:
        return self._active and not self._connection.is_closed

    def commit(self) -> None:
        if self._active:
            self._connection.raw_connection.commit()
            self._active = False

    def rollback(self) -> None:
        if self._active:
            self._connection.raw_connection.rollback()
            self._active = False


class CockroachDBAdapter(Adapter):
    data_model = "relational"
    ir_subset = ("schema", "select")

    def __init__(self) -> None:
        self.dialect = CockroachDBDialect()

    @property
    def id(self) -> str:
        return "cockroachdb"

    @property
    def display_name(self) -> str:
        return "CockroachDB"

    @property
    def package_version(self) -> str:
        from oq_adapters.cockroachdb import __version__

        return __version__

    def capabilities(self) -> CapabilityReport:
        from oq_adapters.cockroachdb import __version__

        return build_report(
            adapter=self.id,
            adapter_version=__version__,
            engine="CockroachDB",
            tested_versions=[],
            capabilities=COCKROACH_CAPS,
            types=COCKROACH_TYPES,
            limitations=[
                "No tested engine version is claimed in this environment.",
                "Serialization failures (SQLSTATE 40001) are retryable; the adapter reports this but does not retry writes.",
                "VECTOR is version-dependent and is not advertised.",
                "No PostgreSQL-style stored procedures.",
            ],
        )

    def connect(self, config: ConnectionConfig, *, secrets: SecretProvider) -> Connection:
        if config.adapter != "cockroachdb":
            raise AdapterError(AdapterErrorCode.CONNECTION, "Expected a cockroachdb config.")
        if psycopg is None:
            raise AdapterError(
                AdapterErrorCode.CONNECTION,
                "psycopg is not installed. Install oq-adapter-cockroachdb[driver].",
            )
        if not config.host:
            raise AdapterError(AdapterErrorCode.CONNECTION, "CockroachDB requires a host.")
        kwargs: dict[str, Any] = {
            "host": config.host,
            "port": config.port or 26257,
            "dbname": config.database or "defaultdb",
            "user": config.user,
            "password": secrets.get("password"),
            "connect_timeout": int(config.options.get("connect_timeout", "10")),
            "sslrootcert": config.sslrootcert,
            "sslcert": config.sslcert,
            "sslkey": config.sslkey,
        }
        if config.sslmode:
            map_mode = {
                "disable": "disable",
                "require": "require",
                "verify-ca": "verify-ca",
                "verify-full": "verify-full",
                "prefer": "prefer",
                "allow": "allow",
            }
            kwargs["sslmode"] = map_mode.get(config.sslmode, "require")
        kwargs = {key: value for key, value in kwargs.items() if value is not None}
        try:
            raw = psycopg.connect(**kwargs, autocommit=False)
        except Exception as exc:
            raise self._error(exc, "connect") from exc
        return CockroachDBConnection(config, raw)

    def detect_version(self, connection: Connection) -> EngineVersion:
        conn = self._require(connection)
        cursor = conn.execute("SELECT version()")
        try:
            raw = str(cursor.fetchone()[0])
        finally:
            cursor.close()
        import re

        match = re.search(r"CockroachDB CCL v(\d+)\.(\d+)\.(\d+)", raw)
        return EngineVersion(
            product="CockroachDB",
            version=raw,
            major=int(match.group(1)) if match else 0,
            minor=int(match.group(2)) if match else 0,
            patch=int(match.group(3)) if match else 0,
        )

    def close(self, connection: Connection) -> None:
        if isinstance(connection, CockroachDBConnection):
            with contextlib.suppress(Exception):
                connection.close()

    def inspect_schema(self, connection: Connection) -> SchemaDocument:
        conn = self._require(connection)
        rows = self._fetch(
            conn,
            """
            SELECT c.table_name, c.column_name, c.data_type, c.is_nullable,
                   c.character_maximum_length, c.numeric_precision, c.numeric_scale,
                   c.column_default, c.is_identity, c.ordinal_position
            FROM information_schema.columns c
            WHERE c.table_schema = current_schema()
            ORDER BY c.table_name, c.ordinal_position
            """,
        )
        pk_rows = self._fetch(
            conn,
            """
            SELECT tc.table_name, kcu.column_name
            FROM information_schema.table_constraints tc
            JOIN information_schema.key_column_usage kcu
              ON kcu.constraint_catalog = tc.constraint_catalog
             AND kcu.constraint_schema = tc.constraint_schema
             AND kcu.constraint_name = tc.constraint_name
            WHERE tc.constraint_type = 'PRIMARY KEY' AND tc.table_schema = current_schema()
            ORDER BY tc.table_name, kcu.ordinal_position
            """,
        )
        fk_rows = self._fetch(
            conn,
            """
            SELECT tc.table_name, kcu.column_name, ccu.table_name, ccu.column_name,
                   rc.update_rule, rc.delete_rule, tc.constraint_name
            FROM information_schema.table_constraints tc
            JOIN information_schema.key_column_usage kcu
              ON kcu.constraint_catalog = tc.constraint_catalog
             AND kcu.constraint_schema = tc.constraint_schema
             AND kcu.constraint_name = tc.constraint_name
            JOIN information_schema.constraint_column_usage ccu
              ON ccu.constraint_catalog = tc.constraint_catalog
             AND ccu.constraint_schema = tc.constraint_schema
             AND ccu.constraint_name = tc.constraint_name
            JOIN information_schema.referential_constraints rc
              ON rc.constraint_catalog = tc.constraint_catalog
             AND rc.constraint_schema = tc.constraint_schema
             AND rc.constraint_name = tc.constraint_name
            WHERE tc.constraint_type = 'FOREIGN KEY' AND tc.table_schema = current_schema()
            ORDER BY tc.table_name, tc.constraint_name, kcu.ordinal_position
            """,
        )
        index_rows = self._fetch(
            conn,
            """
            SELECT table_name, index_name, column_name, seq_in_index, is_unique
            FROM information_schema.statistics
            WHERE table_schema = current_schema()
            ORDER BY table_name, index_name, seq_in_index
            """,
        )
        by_table: dict[str, list[tuple[Any, ...]]] = {}
        for row in rows:
            by_table.setdefault(str(row[0]), []).append(row)
        pk_map: dict[str, list[str]] = {}
        for table, column in pk_rows:
            pk_map.setdefault(str(table), []).append(str(column))
        entities: list[Entity] = []
        for table, table_rows in by_table.items():
            attributes = []
            for row in table_rows:
                _, name, native, nullable, char_length, precision, scale, default, identity, _ = row
                _kind, type_obj = _cockroach_type(str(native), char_length, precision, scale)
                attributes.append(
                    Attribute(
                        name=str(name),
                        type=type_obj,
                        nullable=str(nullable).upper() == "YES",
                        primary=str(name) in pk_map.get(table, []),
                        auto=str(identity).upper() == "YES",
                        default=default,
                    )
                )
            entities.append(
                Entity(
                    name=table,
                    attributes=attributes,
                    primary_key=pk_map.get(table, []),
                    indexes=_cockroach_indexes(table, index_rows),
                    constraints=_cockroach_fks(table, fk_rows),
                )
            )
        return SchemaDocument(entities=entities, enums=[], extensions=[])

    def compile_schema(
        self, schema: SchemaDocument, options: CompileOptions | None
    ) -> list[DDLArtifact]:
        result = compile_schema_sql(self.dialect, schema, options or CompileOptions())
        if not result.supported:
            raise AdapterError(
                AdapterErrorCode.CAPABILITY,
                "CockroachDB cannot compile part of the schema.",
                diagnostics=[item.model_dump(mode="json") for item in result.diagnostics],
            )
        return result.artifacts

    def compile_query(
        self, query: QueryDocument, schema: SchemaDocument, options: CompileOptions | None = None
    ) -> PlanDocument:
        result = compile_select_sql(self.dialect, query, schema, options=options)
        parameters = [dict(item) for item in result.parameters]
        return PlanDocument(
            target_adapter=self.id,
            operation=query.operation,
            artifact=Artifact(
                kind="sql", text=result.sql, dialect="cockroachdb", placeholders=parameters
            ),
            parameters=parameters,
            required_capabilities=[CAP_JOINS] if query.joins else [],
            safety=query.safety,
            result_columns=result.result_columns,
            engine_plan={
                "kind": "sql",
                "sql": result.sql,
                "parameter_order": [p["name"] for p in parameters],
            },
            diagnostics=result.diagnostics,
            supported=result.supported,
        )

    def execute(
        self, connection: Connection, plan: PlanDocument, params: Mapping[str, Any]
    ) -> ResultSet:
        conn = self._require(connection)
        if not plan.supported or not plan.artifact.text:
            raise AdapterError(
                AdapterErrorCode.CAPABILITY,
                "Plan is unsupported and was not executed.",
                diagnostics=[item.model_dump(mode="json") for item in plan.diagnostics],
            )
        values = tuple(params[str(entry["name"])] for entry in plan.parameters)
        try:
            cursor = conn.execute(plan.artifact.text, values)
        except Exception as exc:
            raise self._error(exc, "execute") from exc
        try:
            columns = (
                [ResultColumn(str(c[0]), None, True) for c in cursor.description]
                if cursor.description
                else []
            )
            rows = [ResultRow(tuple(_value(v) for v in row)) for row in cursor.fetchall()]
            affected = (
                cursor.rowcount if cursor.rowcount is not None and cursor.rowcount >= 0 else None
            )
        finally:
            cursor.close()
        return ResultSet(columns=columns, rows=rows, affected_rows=affected, warnings=[])

    def begin(
        self, connection: Connection, options: TransactionOptions | None = None
    ) -> Transaction:
        conn = self._require(connection)
        opts = options or TransactionOptions()
        levels = {
            "read_uncommitted": "READ UNCOMMITTED",
            "read_committed": "READ COMMITTED",
            "repeatable_read": "REPEATABLE READ",
            "serializable": "SERIALIZABLE",
        }
        conn.execute(f"SET TRANSACTION ISOLATION LEVEL {levels[opts.isolation.value]}")
        if opts.read_only:
            conn.execute("SET TRANSACTION READ ONLY")
        return CockroachDBTransaction(conn, opts)

    def commit(self, transaction: Transaction) -> None:
        if not isinstance(transaction, CockroachDBTransaction):
            raise AdapterError(AdapterErrorCode.CONNECTION, "Wrong transaction type.")
        transaction.commit()

    def rollback(self, transaction: Transaction) -> None:
        if isinstance(transaction, CockroachDBTransaction):
            with contextlib.suppress(Exception):
                transaction.rollback()

    def _require(self, connection: Connection) -> CockroachDBConnection:
        if not isinstance(connection, CockroachDBConnection):
            raise AdapterError(
                AdapterErrorCode.CONNECTION, "Wrong connection type for CockroachDB."
            )
        return connection

    @staticmethod
    def _fetch(conn: CockroachDBConnection, sql: str) -> list[tuple[Any, ...]]:
        cursor = conn.execute(sql)
        try:
            return list(cursor.fetchall())
        finally:
            cursor.close()

    @staticmethod
    def _error(exc: BaseException, operation: str) -> AdapterError:
        text = redact_message(str(exc))
        sqlstate = str(getattr(exc, "sqlstate", "") or "")
        code = AdapterErrorCode.CONNECTION
        retryable = False
        if sqlstate in ("23505", "23503", "23514", "23502"):
            code = AdapterErrorCode.CONSTRAINT
        elif sqlstate == "40001":
            code = AdapterErrorCode.TIMEOUT
            retryable = True
        elif sqlstate == "57014":
            code = AdapterErrorCode.CANCELLED
        elif sqlstate in ("28P01", "3D000"):
            code = AdapterErrorCode.AUTH
        elif sqlstate in ("42601", "42P01", "42703"):
            code = AdapterErrorCode.SYNTAX
        elif sqlstate and sqlstate.startswith("08"):
            retryable = True
        return AdapterError(
            code,
            f"CockroachDB {operation} failed: {text}",
            retryable=retryable,
            cause=exc,
            redacted_cause=text,
        )


def _cockroach_type(native: str, char_length: Any, precision: Any, scale: Any) -> tuple[str, Type]:
    name = native.lower()
    if name in ("integer", "int4", "int2", "smallint"):
        return "integer", Type(kind="integer")
    if name in ("bigint", "int8", "int"):
        return "bigint", Type(kind="bigint")
    if name in ("real", "float4"):
        return "float", Type(kind="float")
    if name in ("double precision", "float8", "float"):
        return "double", Type(kind="double")
    if name in ("numeric", "decimal"):
        return "decimal", Type(
            kind="decimal",
            precision=int(precision) if precision else None,
            scale=int(scale) if scale is not None else None,
        )
    if name in ("character varying", "varchar", "character", "char", "text", "string", "bpchar"):
        return "text", Type(kind="text", max_length=int(char_length) if char_length else None)
    if name == "boolean":
        return "boolean", Type(kind="boolean")
    if name == "date":
        return "date", Type(kind="date")
    if name == "time without time zone":
        return "time", Type(kind="time")
    if name in ("timestamp with time zone", "timestamptz"):
        return "timestamp", Type(kind="timestamp", has_timezone=True)
    if name in ("timestamp without time zone", "timestamp"):
        return "datetime", Type(kind="datetime")
    if name == "interval":
        return "duration", Type(kind="duration")
    if name == "uuid":
        return "uuid", Type(kind="uuid")
    if name in ("jsonb", "json"):
        return "json", Type(kind="json")
    if name == "bytea":
        return "binary", Type(kind="binary")
    if name in ("geography", "geometry"):
        return "geo", Type(kind="geo")
    if name.endswith("[]"):
        return "list", Type(kind="list")
    if name.startswith("vector"):
        return "vector", Type(kind="vector")
    return "text", Type(kind="text")


def _cockroach_indexes(table: str, rows: list[tuple[Any, ...]]) -> list[Index]:
    grouped: dict[str, list[tuple[Any, ...]]] = {}
    for row in rows:
        if str(row[0]) == table and str(row[1]) != "primary":
            grouped.setdefault(str(row[1]), []).append(row)
    return [
        Index(
            name=name,
            columns=[str(item[2]) for item in sorted(items, key=lambda item: int(item[3] or 0))],
            unique=bool(items[0][4]),
            kind="btree",
        )
        for name, items in grouped.items()
    ]


def _cockroach_fks(table: str, rows: list[tuple[Any, ...]]) -> list[Constraint]:
    grouped: dict[str, list[tuple[Any, ...]]] = {}
    for row in rows:
        if str(row[0]) == table:
            grouped.setdefault(str(row[6]), []).append(row)
    return [
        Constraint(
            kind="foreign_key",
            columns=[str(item[1]) for item in items],
            reference=str(items[0][2]),
            referenced_columns=[str(item[3]) for item in items],
            on_update=str(items[0][4]),
            on_delete=str(items[0][5]),
        )
        for items in grouped.values()
    ]


def _value(value: Any) -> Any:
    if isinstance(value, memoryview):
        return bytes(value)
    if isinstance(value, (Decimal, date, datetime, time, bytes)):
        return value
    return value
