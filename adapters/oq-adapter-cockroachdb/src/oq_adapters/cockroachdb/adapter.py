class CockroachDBDialect(SqlDialect):
    adapter_id = "cockroachdb"
    engine = "CockroachDB"
    quote_open = '"'
    quote_close = '"'
    max_identifier_length = 63
    placeholder_style = "format"
    supports_full_join = True
    supports_null_ordering = True
    supports_ilike = True
    supports_returning = True
    supports_auto_increment = True

    def type_sql(self, type_obj: Any) -> str | None:
        kind = type_kind(type_obj)
        if kind in ("integer", "int"):
            return "INT4"
        if kind in ("bigint", "reference"):
            return "INT8"
        if kind == "float":
            return "FLOAT4"
        if kind == "double":
            return "FLOAT8"
        if kind == "decimal":
            precision = getattr(type_obj, "precision", None)
            scale = getattr(type_obj, "scale", None)
            if precision and scale is not None:
                return f"DECIMAL({int(precision)},{int(scale)})"
            return "DECIMAL"
        if kind == "text":
            return "STRING"
        if kind == "boolean":
            return "BOOL"
        if kind == "date":
            return "DATE"
        if kind == "time":
            return "TIME"
        if kind in ("timestamp", "datetime"):
            return "TIMESTAMPTZ" if getattr(type_obj, "has_timezone", False) else "TIMESTAMP"
        if kind == "duration":
            return "INTERVAL"
        if kind == "uuid":
            return "UUID"
        if kind == "email":
            return "STRING"
        if kind == "url":
            return "STRING"
        if kind in ("json", "map"):
            return "JSONB"
        if kind == "binary":
            return "BYTES"
        if kind == "geo":
            return "GEOGRAPHY"
        if kind in ("list", "array"):
            return "STRING[]"
        if kind == "set":
            return "STRING[]"
        if kind == "vector":
            dimension = getattr(type_obj, "dimension", None)
            return f"VECTOR({int(dimension)})" if dimension else None
        if kind == "enum":
            return "STRING"
        return None

    def auto_sql(self, attr: Any, type_sql: str) -> str | None:
        if type_kind(attr.type) not in ("integer", "int", "bigint"):
            return None
        return "GENERATED BY DEFAULT AS IDENTITY"

    def bind_placeholder(self, index: int, hint: str, label: str) -> str:
        return "%s"


